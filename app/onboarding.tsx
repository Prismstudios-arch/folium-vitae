// Screen 3: Setup
function Screen3({ onNext }: { onNext: () => void }) {
  const [hasChildren, setHasChildren] = useState(false);

  return (
    <View style={styles.screen}>
      <View style={styles.topSection}>
        <Text style={styles.emoji}>⚙️</Text>
        <Text style={styles.title}>Quick Setup</Text>
      </View>

      <View style={styles.middleSection}>
        <Text style={styles.setupQuestion}>Do you have kids or pets at home?</Text>
        <Text style={styles.setupSubtext}>
          This helps us warn you about toxic plants.
        </Text>

        <View style={styles.toggleButtons}>
          <TouchableOpacity
            style={[styles.toggleButton, !hasChildren && styles.toggleActive]}
            onPress={() => setHasChildren(false)}
          >
            <Text style={[styles.toggleText, !hasChildren && styles.toggleTextActive]}>
              No
            </Text>
          </TouchableOpacity>

          <TouchableOpacity
            style={[styles.toggleButton, hasChildren && styles.toggleActive]}
            onPress={() => setHasChildren(true)}
          >
            <Text style={[styles.toggleText, hasChildren && styles.toggleTextActive]}>
              Yes
            </Text>
          </TouchableOpacity>
        </View>
      </View>

      <View style={styles.bottomSection}>
        <Button label="Next" onPress={onNext} />
      </View>
    </View>
  );
}

