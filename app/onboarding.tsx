import {
  View,
  Text,
  StyleSheet,
  ScrollView,
  TouchableOpacity,
  TextInput,
  Dimensions,
} from "react-native";
import { useRef, useState } from "react";
import { useRouter } from "expo-router";
import Animated, { FadeInDown, FadeOutUp } from "react-native-reanimated";
import { Colors, Spacing, Typography } from "@constants/theme";
import { Button } from "@components/Button";
import { completeOnboarding } from "@services/userPreferences";

const { height } = Dimensions.get("window");

type Screen = "welcome" | "promise" | "setup" | "referral";

export default function OnboardingScreen() {
  const router = useRouter();
  const scrollViewRef = useRef<ScrollView>(null);
  const [currentScreen, setCurrentScreen] = useState<Screen>("welcome");
  const [referralSource, setReferralSource] = useState("");

  const handleNext = () => {
    const screens: Screen[] = ["welcome", "promise", "setup", "referral"];
    const currentIndex = screens.indexOf(currentScreen);
    if (currentIndex < screens.length - 1) {
      setCurrentScreen(screens[currentIndex + 1]);
    }
  };

  const handleComplete = async () => {
    try {
      await completeOnboarding(referralSource || undefined);
      router.replace("/scan");
    } catch (error) {
      console.error("Failed to complete onboarding:", error);
    }
  };

  return (
    <ScrollView
      ref={scrollViewRef}
      style={styles.container}
      contentContainerStyle={styles.contentContainer}
      scrollEnabled={false}
    >
      {currentScreen === "welcome" && (
        <Animated.View entering={FadeInDown}>
          <Screen1 onNext={handleNext} />
        </Animated.View>
      )}

      {currentScreen === "promise" && (
        <Animated.View entering={FadeInDown}>
          <Screen2 onNext={handleNext} />
        </Animated.View>
      )}

      {currentScreen === "setup" && (
        <Animated.View entering={FadeInDown}>
          <Screen3 onNext={handleNext} />
        </Animated.View>
      )}

      {currentScreen === "referral" && (
        <Animated.View entering={FadeInDown}>
          <Screen4
            referralSource={referralSource}
            onChangeReferral={setReferralSource}
            onComplete={handleComplete}
          />
        </Animated.View>
      )}
    </ScrollView>
  );
}

// Screen 1: Welcome
function Screen1({ onNext }: { onNext: () => void }) {
  return (
    <View style={styles.screen}>
      <View style={styles.topSection}>
        <Text style={styles.emoji}>🌱</Text>
        <Text style={styles.title}>Welcome to Verdure</Text>
        <Text style={styles.subtitle}>The honest plant identification app</Text>
      </View>

      <View style={styles.middleSection}>
        <FeatureRow icon="📸" text="Identify plants from photos" />
        <FeatureRow icon="📚" text="Get curated care advice" />
        <FeatureRow icon="🌿" text="Track your plant collection" />
      </View>

      <View style={styles.bottomSection}>
        <Button label="Get Started" onPress={onNext} />
      </View>
    </View>
  );
}

